export function getPropertyBySlug(slug: string) {
  return properties.find((p) => p.slug === slug && p.published);
}

export function getPropertiesByCity(citySlug: string) {
  return properties.filter((p) => p.citySlug === citySlug && p.published);
}

export function getPropertiesByState(stateSlug: string) {
  return properties.filter((p) => p.stateSlug === stateSlug && p.published);
}

export function getFeaturedProperties() {
  return properties.filter((p) => p.featured && p.published);
}

export function getPropertiesByCategory(category: string) {
  return properties.filter((p) => p.categories.includes(category as never) && p.published);
}

export function getRelatedProperties(property: Property, count = 3) {
  return properties
    .filter(
      (p) =>
        p.slug !== property.slug &&
        p.published &&
        (p.stateSlug === property.stateSlug ||
          p.categories.some((c) => property.categories.includes(c)))
    )
    .slice(0, count);
}
